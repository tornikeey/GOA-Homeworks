let num = 1;

while (num <= 10) {
  console.log(num);
  num++;
}

// For Loop-ს ვიყენებთ მაშინ, როდესაც ვიცით თუ რამდენი ინტერაცია უნდა შევასრულოთ ერთ კონკრეტულ მოცემულობაში, ხოლო While Loop-ს ვიყენებთ მაშინ როცა არ ვიცით თუ რამდენი გამეორებაა საჭირო
// მაგრამ ვიცით პირობა

let count = 0;

do {
  count++;
  console.log(count);
} while (count < 10);

// While-სა და Do While-ს შორის არის ის განსხვავება, რომ Do While კოდის ბლოკში ციკლი ერთხელ მაინც შესრულდება.